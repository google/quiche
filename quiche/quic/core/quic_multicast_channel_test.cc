// One frame as it sits in a packet: the type varint, then the body.
std::string Frame(uint64_t type, absl::string_view body) {
  char buf[8];
  QuicDataWriter writer(sizeof(buf), buf);
  EXPECT_TRUE(writer.WriteVarInt62(type));
  return std::string(buf, writer.length()) + std::string(body);
}

// STREAM with offset, length and FIN, as Q writes it.
std::string StreamFrame(QuicStreamId id, uint64_t offset,
                        absl::string_view data) {
  char buf[64];
  QuicDataWriter writer(sizeof(buf), buf);
  EXPECT_TRUE(writer.WriteVarInt62(0x0f) && writer.WriteVarInt62(id) &&
              writer.WriteVarInt62(offset) &&
              writer.WriteVarInt62(data.size()) &&
              writer.WriteStringPiece(data));
  return std::string(buf, writer.length());
}

absl::Span<const uint8_t> Bytes(absl::string_view s) {
  return absl::MakeConstSpan(reinterpret_cast<const uint8_t*>(s.data()),
                             s.size());
}

std::string Sha256(absl::string_view data) {
  std::string out(SHA256_DIGEST_LENGTH, '\0');
  SHA256(reinterpret_cast<const uint8_t*>(data.data()), data.size(),
         reinterpret_cast<uint8_t*>(out.data()));
  return out;
}

// Seals |payload| as channel packet |pn| the way Q's ChannelSendState does
// (first byte 0x47: short header, key phase 1, 4-byte packet number), with
// the C10 secrets. SealMatchesQ checks it against Q's own bytes. A rotated
// key passes its secret byte and its key phase (the sequence's parity).
std::string Seal(uint64_t pn, absl::string_view payload,
                 char key_byte = '\x22', bool key_phase = true) {
  std::unique_ptr<QuicEncrypter> encrypter =
      QuicEncrypter::CreateFromCipherSuite(TLS1_3_CK_AES_128_GCM_SHA256);
  const std::string key_secret(32, key_byte);
  const std::string header_secret(32, '\x11');
  CryptoUtils::SetKeyAndIV(EVP_sha256(), Bytes(key_secret),
                           ParsedQuicVersion::RFCv1(), encrypter.get());
  std::string hp_key(encrypter->GetKeySize(), '\0');
  EXPECT_TRUE(CryptoUtils::GenerateHeaderProtectionKey(
      EVP_sha256(), Bytes(header_secret), ParsedQuicVersion::RFCv1(),
      absl::MakeSpan(reinterpret_cast<uint8_t*>(hp_key.data()),
                     hp_key.size())));
  EXPECT_TRUE(encrypter->SetHeaderProtectionKey(hp_key));
  std::string packet =
      (key_phase ? "\x47" : "\x43") + std::string(kChannelId);
  const size_t pn_offset = packet.size();
  for (int shift = 24; shift >= 0; shift -= 8) {
    packet.push_back(static_cast<char>(pn >> shift));
  }
  std::string sealed(payload.size() + 16, '\0');
  size_t sealed_length = 0;
  EXPECT_TRUE(encrypter->EncryptPacket(pn, packet, payload, sealed.data(),
                                       &sealed_length, sealed.size()));
  packet += sealed.substr(0, sealed_length);
  const std::string mask = encrypter->GenerateHeaderProtectionMask(
      absl::string_view(packet).substr(pn_offset + 4, 16));
  packet[0] ^= mask[0] & 0x1f;
  for (size_t i = 0; i < 4; ++i) {
    packet[pn_offset + i] ^= mask[1 + i];
  }
  return packet;
}

// MC_INTEGRITY (0xff3e805): channel ID, start, count, count hashes.
struct Integrity {
  uint64_t start = 0;
  std::string hashes;
};
Integrity ParseIntegrity(absl::string_view hex) {
  std::string frame = Hex(hex);
  quiche::QuicheDataReader reader(frame);
  uint64_t type = 0, count = 0;
  uint8_t cid_len = 0;
  absl::string_view cid, hashes;
  Integrity out;
  EXPECT_TRUE(reader.ReadVarInt62(&type) && reader.ReadUInt8(&cid_len) &&
              reader.ReadStringPiece(&cid, cid_len) &&
              reader.ReadVarInt62(&out.start) && reader.ReadVarInt62(&count));
  hashes = reader.ReadRemainingPayload();
  EXPECT_EQ(type, 0xff3e805u);
  EXPECT_EQ(cid, kChannelId);
  EXPECT_EQ(hashes.size(), 32 * count);
  out.hashes = std::string(hashes);
  return out;
}

