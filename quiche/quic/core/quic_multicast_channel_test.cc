// C10's capture: 23 sends on streams 4003 and 4007, body from offset 10, the
// last packet carrying both FINs; send 9 (PN 14, stream 4007 bytes 74-89)
// never arrives, though its hash does. Each packet arrives before its hash.
TEST_F(QuicMulticastChannelTest, CaptureTwoStreamsWithGap) {
  Key();
  std::vector<QuicMulticastChannelFrame> frames;
  size_t packets = 0;
  for (const CaptureVector& v : kCapture) {
    if (!v.packet_hex.empty()) {
      ++packets;
      EXPECT_TRUE(Packet(v.packet_hex).empty());
    }
    for (QuicMulticastChannelFrame& f : Hash(v.integrity_hex)) {
      frames.push_back(std::move(f));
    }
  }
  EXPECT_EQ(packets, 22u);
  EXPECT_EQ(channel_->stats().delivered_packets, 22u);
  EXPECT_EQ(channel_->pending_packets(), 0u);
  ASSERT_EQ(frames.size(), 23u);
  std::map<QuicStreamId, std::string> body;
  std::map<QuicStreamId, uint64_t> fin;
  for (const QuicMulticastChannelFrame& f : frames) {
    ASSERT_FALSE(f.reset);
    std::string& b = body[f.stream_id];
    b.resize(std::max<size_t>(b.size(), f.offset + f.data.size()), '\0');
    b.replace(f.offset, f.data.size(), f.data);
    if (f.fin) fin[f.stream_id] = f.offset + f.data.size();
  }
  EXPECT_EQ(fin, (std::map<QuicStreamId, uint64_t>{{4003, 202}, {4007, 202}}));
  EXPECT_EQ(body[4003].substr(10, 16), "A00:tick-0123456");
  EXPECT_EQ(body[4003].find('\0', 10), std::string::npos);
  EXPECT_EQ(body[4007].find('\0', 10), 74u);
  EXPECT_EQ(body[4007].find_first_not_of('\0', 74), 90u);
}

// The same capture, packets first, then every hash in one MC_INTEGRITY.
TEST_F(QuicMulticastChannelTest, CaptureWithOneBatchedIntegrity) {
  Key();
  std::string hashes;
  uint64_t start = 0;
  for (const CaptureVector& v : kCapture) {
    if (!v.packet_hex.empty()) {
      EXPECT_TRUE(Packet(v.packet_hex).empty());
    }
    Integrity i = ParseIntegrity(v.integrity_hex);
    if (hashes.empty()) start = i.start;
    EXPECT_EQ(i.start, start + hashes.size() / 32);
    hashes += i.hashes;
  }
  EXPECT_EQ(channel_->pending_packets(), 22u);
  EXPECT_EQ(channel_->OnIntegrity(start, hashes, now_).size(), 23u);
  EXPECT_EQ(channel_->stats().delivered_packets, 22u);
  EXPECT_EQ(channel_->pending_packets(), 0u);
}

// T2: q-cli's fixed-secret capture of our own server's channel (S->G in the
// B7 bed), 150 packets that decode08.py also decodes. Each is one clock tick:
// stream 4003 + 4 x PN from offset 10 with FIN, body "<unix ms> <21 + PN>".
// MC_INTEGRITY rides the TLS connection, so the capture has none and the
// test supplies each packet's SHA-256.
TEST_F(QuicMulticastChannelTest, LiveCaptureOfOurServer) {
  Key();
  for (uint64_t pn = 0; pn < std::size(kLive08); ++pn) {
    const std::string packet = Hex(kLive08[pn]);
    EXPECT_TRUE(channel_->OnIntegrity(pn, Sha256(packet), now_).empty());
    std::vector<QuicMulticastChannelFrame> frames =
        channel_->OnPacket(packet, ECN_NOT_ECT, now_);
    ASSERT_EQ(frames.size(), 1u) << pn;
    EXPECT_EQ(frames[0].packet_number, pn);
    EXPECT_EQ(frames[0].stream_id, 4003 + 4 * pn);
    EXPECT_EQ(frames[0].offset, 10u);
    EXPECT_TRUE(frames[0].fin);
    EXPECT_EQ(frames[0].data.size(), 14 + absl::StrCat(21 + pn).size());
    EXPECT_TRUE(absl::EndsWith(frames[0].data, absl::StrCat(" ", 21 + pn)))
        << frames[0].data;
  }
  EXPECT_EQ(channel_->stats().delivered_packets, std::size(kLive08));
  std::optional<QuicMcAck> ack = channel_->TakeAck();
  ASSERT_TRUE(ack.has_value());
  EXPECT_EQ(ack->largest_acknowledged, 149u);
  EXPECT_EQ(ack->first_ack_range, 149u);
  EXPECT_TRUE(ack->ranges.empty());
}

